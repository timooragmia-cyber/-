#!/usr/bin/env bash
# One-command installation on a fresh Ubuntu 24.04 server (AWS EC2 or similar).
#
#   cd /opt/ta && sudo bash deploy/install.sh
#
# Asks for: the domain, the e-mail for certificate notices, the advisor's login e-mail.
# Non-interactive: DOMAIN=… ACME_EMAIL=… ADVISOR_EMAIL=… sudo -E bash deploy/install.sh
#
# Safe to run again: existing secrets (.env, backup.env) are never overwritten, migrations and
# the seed are idempotent, and nothing is deleted.
#
# Options:
#   --skip-system   do not install packages / Docker / firewall (already done)
#   --no-build      use images that are already built (rehearsal)
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT="$(pwd)"

SKIP_SYSTEM=0; NO_BUILD=0
for a in "$@"; do
  case "$a" in
    --skip-system) SKIP_SYSTEM=1 ;;
    --no-build) NO_BUILD=1 ;;
    *) echo "unknown option $a"; exit 2 ;;
  esac
done

say() { printf '\n\033[1;34m==> %s\033[0m\n' "$1"; }
die() { printf '\033[31mERROR: %s\033[0m\n' "$1" >&2; exit 1; }
[ "$(id -u)" = 0 ] || die "run with sudo: sudo bash deploy/install.sh"
[ -f docker-compose.yml ] && [ -f Dockerfile ] || die "run from the repository folder (e.g. /opt/ta)"

# ── 1. System ────────────────────────────────────────────────────────────────────────────
if [ "$SKIP_SYSTEM" = 0 ]; then
  say "System packages and security updates"
  . /etc/os-release
  [ "${ID:-}" = ubuntu ] || die "Ubuntu is required (found ${ID:-unknown})"
  export DEBIAN_FRONTEND=noninteractive
  apt-get update -q
  apt-get install -y -q ca-certificates curl git openssl ufw unattended-upgrades cron
  dpkg-reconfigure -f noninteractive unattended-upgrades >/dev/null 2>&1 || true

  if ! command -v docker >/dev/null 2>&1; then
    say "Docker Engine (official repository)"
    install -m 0755 -d /etc/apt/keyrings
    curl -fsSL https://download.docker.com/linux/ubuntu/gpg -o /etc/apt/keyrings/docker.asc
    chmod a+r /etc/apt/keyrings/docker.asc
    echo "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.asc] https://download.docker.com/linux/ubuntu ${VERSION_CODENAME} stable" > /etc/apt/sources.list.d/docker.list
    apt-get update -q
    apt-get install -y -q docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin
  fi
  if [ ! -f /etc/docker/daemon.json ]; then
    # Container logs (incl. Caddy access logs with client IPs) are rotated: max ~150 MB per container.
    printf '{\n  "log-driver": "json-file",\n  "log-opts": { "max-size": "50m", "max-file": "3" }\n}\n' > /etc/docker/daemon.json
    systemctl restart docker
  fi
  systemctl enable --now docker cron >/dev/null 2>&1 || true

  say "Firewall (SSH, HTTP, HTTPS only)"
  ufw allow OpenSSH >/dev/null && ufw allow 80/tcp >/dev/null && ufw allow 443 >/dev/null && ufw --force enable >/dev/null \
    || echo "  (ufw could not be enabled here — the AWS security group still protects the server)"
fi
command -v docker >/dev/null 2>&1 && docker compose version >/dev/null 2>&1 || die "Docker with the compose plugin is required"

# ── 2. Configuration ─────────────────────────────────────────────────────────────────────
say "Configuration"
val() { grep -E "^$1=" "$2" 2>/dev/null | tail -n 1 | cut -d= -f2- | sed -e 's/^"//' -e 's/"$//'; }
ask() { # ask VAR "question" — keeps an existing value from env or .env
  local cur="${!1:-}"; [ -z "$cur" ] && cur="$(val "$1" .env)"
  if [ -z "$cur" ]; then read -r -p "  $2: " cur; fi
  [ -n "$cur" ] || die "$1 is required"
  printf -v "$1" '%s' "$cur"
}
ask DOMAIN "Domain for the system (e.g. app.ta-mortgages.co.il)"
ask ACME_EMAIL "E-mail for certificate notices"
ADVISOR_EMAIL="${ADVISOR_EMAIL:-$(val SEED_ADVISOR_EMAIL .env)}"
[ -n "$ADVISOR_EMAIL" ] && [ "$ADVISOR_EMAIL" != "advisor@example.test" ] || read -r -p "  Advisor login e-mail: " ADVISOR_EMAIL
[[ "$DOMAIN" =~ ^[A-Za-z0-9.-]+$ ]] || die "invalid domain: $DOMAIN"
[[ "$ADVISOR_EMAIL" == *@* ]] || die "invalid e-mail: $ADVISOR_EMAIL"

if [ "$DOMAIN" != localhost ]; then
  public_ip="$(curl -fsS --max-time 5 https://checkip.amazonaws.com 2>/dev/null | tr -d '[:space:]' || true)"
  dns_ip="$(getent ahostsv4 "$DOMAIN" 2>/dev/null | awk 'NR==1 {print $1}' || true)"
  if [ -n "$public_ip" ] && [ "$dns_ip" != "$public_ip" ]; then
    echo "  DNS: $DOMAIN → ${dns_ip:-(none)}, but this server is $public_ip."
    echo "  Create an A record $DOMAIN → $public_ip first, or Caddy cannot obtain a certificate."
    read -r -p "  Continue anyway? [y/N] " yn; [ "$yn" = y ] || exit 1
  fi
fi

ADVISOR_PASSWORD=""
if [ ! -f .env ]; then
  say "Generating secrets (.env)"
  rnd() { openssl rand -base64 32 | tr -d '\n'; }
  ADVISOR_PASSWORD="$(openssl rand -base64 18 | tr -d '/+=\n')"
  umask 077
  cat > .env <<EOF
# Generated by deploy/install.sh on $(date -u +%F). KEEP A COPY IN THE OFFICE PASSWORD MANAGER:
# without FIELD_ENCRYPTION_KEYS the encrypted data and files cannot be recovered, even from backups.
POSTGRES_PASSWORD="$(openssl rand -hex 24)"
DATABASE_URL="postgresql://ta:unused@db:5432/ta_platform?schema=public"
FIELD_ENCRYPTION_KEYS="v1:$(rnd)"
BLIND_INDEX_KEY="$(rnd)"
SESSION_IDLE_MINUTES=30
SESSION_ABSOLUTE_HOURS=12
APP_URL="https://$DOMAIN"
TOTP_ISSUER="T.A Mortgages"
UPLOAD_DIR="/app/storage/uploads"
DOMAIN="$DOMAIN"
ACME_EMAIL="$ACME_EMAIL"
SEED_ADVISOR_EMAIL="$ADVISOR_EMAIL"
SEED_DEMO_DATA="false"
EOF
  umask 022
else
  echo "  .env exists — keeping all secrets as they are"
  grep -q '^SEED_DEMO_DATA="\?false' .env || die ".env must contain SEED_DEMO_DATA=\"false\" in production"
fi
chmod 600 .env
if [ ! -f backup.env ]; then
  cp backup.env.example backup.env
  echo "  backup.env created from the example — fill it in to enable backups (docs/DEPLOYMENT.md §5)"
fi
chmod 600 backup.env

# ── 3. Build and start ───────────────────────────────────────────────────────────────────
C=(docker compose)
if [ "$NO_BUILD" = 0 ]; then
  say "Building images (several minutes the first time)"
  "${C[@]}" --profile tools build
fi
say "Database and migrations"
"${C[@]}" up -d db
"${C[@]}" run --rm migrate
say "Reference data and advisor login"
if [ -n "$ADVISOR_PASSWORD" ]; then
  "${C[@]}" run --rm -e SEED_ADVISOR_PASSWORD="$ADVISOR_PASSWORD" -e SEED_DEMO_DATA=false tools db:seed
else
  "${C[@]}" run --rm -e SEED_DEMO_DATA=false tools db:seed
fi
say "Starting app and HTTPS"
"${C[@]}" up -d app caddy
for _ in $(seq 1 60); do
  [ "$(docker inspect -f '{{.State.Health.Status}}' "$("${C[@]}" ps -q app)" 2>/dev/null)" = healthy ] && break
  sleep 2
done

# ── 4. Scheduled jobs ────────────────────────────────────────────────────────────────────
say "Scheduled jobs (nightly backup 02:15, privacy purge 03:45, server time)"
cat > /etc/cron.d/ta-platform <<EOF
# T.A Mortgages platform — installed by deploy/install.sh
SHELL=/bin/bash
PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin
15 2 * * * root cd $ROOT && if grep -q '^S3_BUCKET="\\?[^"]' backup.env; then docker compose run --rm backup /usr/local/bin/backup.sh; else echo "backup skipped: backup.env not configured"; fi >> /var/log/ta-backup.log 2>&1
45 3 * * * root cd $ROOT && docker compose run --rm tools privacy:purge >> /var/log/ta-purge.log 2>&1
EOF
chmod 644 /etc/cron.d/ta-platform

# ── 5. Verify and summary ────────────────────────────────────────────────────────────────
say "Verification"
VERIFY_INSECURE="$([ "$DOMAIN" = localhost ] && echo 1 || echo 0)" bash deploy/verify.sh || true

echo
echo "────────────────────────────────────────────────────────────────────────"
echo " Open:      https://$DOMAIN"
echo " Advisor:   $ADVISOR_EMAIL"
if [ -n "$ADVISOR_PASSWORD" ]; then
  echo " Password:  $ADVISOR_PASSWORD     ← shown ONCE. Save it, then change it after first login."
fi
echo " Next:      1) save .env in the password manager   2) log in and enroll 2FA"
echo "            3) fill backup.env (docs/DEPLOYMENT.md §5)  4) work through docs/UNVERIFIED.md"
echo "────────────────────────────────────────────────────────────────────────"
